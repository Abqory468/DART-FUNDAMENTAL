void main(List<String> args) {
  /**
   * == "sama dengan"
   * != "tidak sama dengan"
   * <  "kurang dari"
   * >  "lebih dari"
   * <= "kurang dari sama dengan"
   * >= "lebih dari sama dengan"
   * 
   * --> --> Logic Gate <-- <--
   * || "atau" logic "or"
   * && "dan" logic "and"
   * !  "not" atau "bukan"
   */

  var a = 3;
  var b = 2;

  print(a == b); //false
  print(a != b); //true
  print(a < b); //false
  print(a > b); //true
  print(a <= b); //false
  print(a >= b); //true

}