/**
 * Abstract Class adalah sebuah class yang tidak dapat dibuat menjadi objek (instance)
 * TETAPI dapat digunakan sebagai class untuk ParentClass (SuperClass) untuk diwariskan kepada
 * class lain
 * 
 * dengan kata lain:
 * 1. dapat diwarisi (inheritance)
 * 2. dapat memiliki properties
 * 3. dapat memiliki methods
 * 4. tidak dapat dibuat menjadi objek
 * 
 * Abstract Class dijadikan sebagai kerangka dasar yang akan digunakan
 * oleh class turunannya
 * 
 * ada kata kunci abstract 
 * abstract class NamaClass {}
 */