/**
 * paradigma adalah pola pikir, kerangka, cara pandang
 * paradigma oop = didasari pada konsep objek yang memiliki atribut
 * serta dapat melakukan operasi atau prosedur tertentu
 * 
 * 4 pilar oop
 * - encapsulation
 * - abstraction
 * - inheritance
 * - polymorphism
 * 
 * => encapsulation
 * = ibarat -> sebuah kantong yang menyimpan sesuatu dalam pemrograman
 * = berfungsi -> mengumpulkan data dan tidak dapat diakses langsung dari luar
 * = pada kasus -> "Ucup Guerero" kita tidak bisa mengubah berat badan dari Ucup,
 *                 tapi kita bisa menambahkannya melalui fungsi / method makan().
 * 
 * => Abstraction
 * = Bisa dibilang penerapan alami dari Encapsulation
 * = yang mana, Abstraction bearti sebuah objek yang hanya menunjukkan operasinya 
 *   secara high-level.
 * = Misalnya -> kita hanya cukup tau bagaimana "Ucup Guerero" makan, namun kita 
 *               tidak tau bagaimana sistem metabolism biologis dalam tubuh si ucup, 
 *               yang membuat berat badan si Ucup bertambah.
 * 
 * => Inheritance
 * = Beberapa objek bisa memiliki beberapa karakteristik atau perilaku yang sama
 * = Namun mereka bukanlah objek yang sama
 * = Inheritance pada "Ucup Guerero" memiliki sifat dan perilaku yang umum dengan 
 *   Manusia yang lain, seperti; berat, warna kulit, tinggi. Maka "Ucup Guerero" 
 *   sebagai objek turunan (SubClass).
 *   Induk class-nya disebut Manusia (SuperClass/ParentClass).
 * 
 * => Polymorphism
 * = Berarti "Banyak Bentuk"
 * = Objek dapat memiliki bentuk atau implementasi yang berbeda-beda pada satu metode yang sama
 * = Misal; Manusia bergerak, akan tetapi cara gerak Ucup Guerero dan Kenzie Samurai berbeda
 */